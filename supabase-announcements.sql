-- 69th FAMILY: additive announcement table.
-- This does not alter or delete existing Attendance Tracker / Feedback tables.
-- Run only after confirming you are in the intended existing Supabase project.
create table if not exists public.family_announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 180),
  body text not null check (char_length(trim(body)) between 1 and 10000),
  category text not null default 'Announcement',
  is_published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.family_announcements enable row level security;

-- Students/visitors may read only published announcements.
drop policy if exists "Public can read published family announcements"
  on public.family_announcements;
create policy "Public can read published family announcements"
  on public.family_announcements
  for select
  to anon, authenticated
  using (is_published = true);

-- Intentionally no public INSERT / UPDATE / DELETE policy.
-- Admin write permissions must be added only after reviewing the existing
-- project's auth/profile/role schema. Do not make the table publicly writable.
grant select on public.family_announcements to anon, authenticated;
